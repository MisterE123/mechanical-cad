"""Run in two fresh Blender processes: MCAD_RECOVERY_PHASE=capture then restore.

MCAD_RECOVERY_DIR is disposable fixture storage. No .blend or .mcad is saved.
The only extra file is expected.json, generated by the first process for assertions.
"""
import json
import os
import sys
import time
from pathlib import Path
from unittest.mock import patch

import bpy

ROOT = Path(os.environ['MCAD_ROOT'])
FIXTURE = Path(os.environ['MCAD_RECOVERY_DIR'])
PHASE = os.environ['MCAD_RECOVERY_PHASE']
sys.path.insert(0, str(ROOT / 'blender_addon'))
from mechanical_cad_blender import (  # noqa: E402
    dimension_input,
    document_state,
    draft_dispatch,
    execution_lease,
    general_session,
    local_recovery,
    register,
    sketch_session,
    unregister,
)
from mechanical_cad_blender.general_sketch_commands import AddLine, PointRef, PointSeed  # noqa: E402


def wait(owner):
    deadline = time.monotonic() + 60
    while owner.pending is not None and time.monotonic() < deadline:
        owner.tick(bpy.context)
        time.sleep(.01)
    assert owner.pending is None and not owner.error, owner.error


register()
entry = bpy.context.preferences.addons.new()
entry.module = 'mechanical_cad_blender'
prefs = entry.preferences
assert not prefs.local_recovery_enabled
prefs.project_root = str(ROOT)
prefs.python_executable = os.environ['MCAD_PYTHON']
window = bpy.context.window
area = next(a for a in window.screen.areas if a.type == 'VIEW_3D')
region = next(r for r in area.regions if r.type == 'WINDOW')
with patch.object(local_recovery, 'storage_root', return_value=FIXTURE / 'recovery'), bpy.context.temp_override(
    window=window, area=area, region=region,
):
    if PHASE == 'capture':
        part = {
            'schema_version': 1, 'id': 'unsaved_process_recovery', 'name': 'Never saved',
            'units': 'mm', 'parameters': {'width': 24}, 'active_feature': 'pad',
            'features': [
                {'id': 'outline', 'kind': 'sketch_rectangle', 'label': 'Base outline',
                 'inputs': {}, 'params': {'width': 'width', 'height': 15, 'x': 0, 'y': 0, 'z': 0}},
                {'id': 'pad', 'kind': 'extrude', 'label': 'Unsaved solid',
                 'inputs': {'profile': 'outline'}, 'params': {'length': 8}},
            ],
        }
        document_state._commit_candidate(bpy.context, part)
        assert bpy.context.scene.mechanical_cad.status == 'READY'
        assert abs(bpy.context.scene.mechanical_cad.volume - 24 * 15 * 8) < 1e-7
        assert len(json.loads(bpy.context.scene.mechanical_cad.document_json)['features']) == 2
        # Deliberately preserve noncanonical whitespace to verify exact byte binding.
        bpy.context.scene.mechanical_cad.document_json += ' \n'
        owner = general_session.GeneralSession(bpy.context)
        owner.start()
        owner.execute(bpy.context, AddLine(PointSeed(0, 0), PointSeed(10, 0)))
        wait(owner)
        point_id = owner.commands.sketch['lines'][0]['end']
        owner.draft.select_tool('Line')
        owner.accept_point_input(bpy.context, PointRef(point_id), expected_phase=('line', 'start'))
        owner.open_line_length(bpy.context, PointSeed(30, 0), axis='horizontal')
        owner.input_controller.handle(
            dimension_input.InputEvent('A', unicode=' invalid length '),
            approve_raw=lambda action: (owner.update_raw(action.raw) is None),
        )
        prefs.local_recovery_enabled = True
        local_recovery.observe()
        assert local_recovery.status(bpy.context.scene)[0] == 'SNAPSHOT', local_recovery.status(bpy.context.scene)
        rows = local_recovery.store().entries()
        entry = max(rows, key=lambda row: row.sequence)
        record = local_recovery.store().read(entry.scope, entry.slot)
        assert record.draft_json == draft_dispatch.dumps(owner.draft)
        FIXTURE.mkdir(parents=True, exist_ok=True)
        (FIXTURE / 'expected.json').write_text(json.dumps({
            'scope': entry.scope, 'slot': entry.slot, 'canonical': record.document_json,
            'draft': record.draft_json, 'sketch': owner.commands.sketch,
            'pending_length': owner.draft.pending_length,
        }))
        assert not bpy.data.filepath and not bpy.context.scene.mechanical_cad.document_path
        print('LOCAL_RECOVERY_PROCESS_CAPTURE_OK', flush=True)
    elif PHASE == 'restore':
        expected = json.loads((FIXTURE / 'expected.json').read_text())
        original = bpy.context.scene
        original_raw = original.mechanical_cad.document_json
        restored_scene = local_recovery.restore_as_new(bpy.context, expected['scope'], expected['slot'])
        state = restored_scene.mechanical_cad
        assert state.document_json == expected['canonical']
        recovered_part = json.loads(state.document_json)
        assert [feature['id'] for feature in recovered_part['features']] == ['outline', 'pad']
        assert recovered_part['active_feature'] == 'pad'
        assert recovered_part['parameters'] == {'width': 24}
        assert state.status == 'DIRTY' and state.volume == 0
        assert state.sketch_draft_json == expected['draft']
        assert not state.document_path and not bpy.data.filepath
        assert not restored_scene.objects and not sketch_session.active_session()
        assert not execution_lease.is_busy()
        assert original.mechanical_cad.document_json == original_raw
        restored = draft_dispatch.restore(state.sketch_draft_json, state.document_json)
        assert restored.command_draft.sketch == expected['sketch']
        assert restored.pending_length == expected['pending_length']
        owner = general_session.GeneralSession(bpy.context, restored=restored)
        owner.start()  # Explicit Resume; never an automatic recovery side effect.
        assert owner.pending is None and owner.length_attempt is None
        assert owner.input_controller is None and not owner.input_token
        assert not owner.commands.has_current_solution and owner.guarded_evidence is None
        assert owner.expected_prepared is None and not owner.proposal_capture
        assert len(owner.commands.sketch['lines']) == 1
        owner.open_line_length(bpy.context)
        assert owner.input_controller.raw == ' invalid length '
        # Invalid raw input survives, but confers no acceptance or solver authority.
        # Explicitly cancel the unfinished proposal before validating the accepted line.
        owner.cancel_line_proposal()
        owner.check(bpy.context)
        wait(owner)
        assert owner.commands.has_current_solution, 'Explicit Resume Check needs fresh native validation'
        assert len(owner.commands.sketch['lines']) == 1
        assert state.document_json == expected['canonical']
        owner.discard()
        print('LOCAL_RECOVERY_PROCESS_RESTORE_OK', flush=True)
    else:
        raise AssertionError(f'Unknown phase: {PHASE}')
unregister()
