"""Real registered RNA invoke/enum callbacks; not mouse or popup GUI qualification.

Set MCAD_PROJECTION_FIXTURE to a JSON generated by the existing
integration test_associative_projection.projected_document fixture in sidecar Python.
"""

import json
import os
import sys
from pathlib import Path

import bpy

ROOT = Path(os.environ["MCAD_ROOT"])
sys.path.insert(0, str(ROOT / "blender_addon"))
from mechanical_cad_blender import (  # noqa: E402
    document_state,
    projection_repair_ui,
    register,
    solid_operators,
    unregister,
)

captured = {}


class Manager:
    def invoke_props_dialog(self, owner, **kwargs):
        return {"RUNNING_MODAL"}


class DialogContext:
    window_manager = Manager()

    def __getattr__(self, key):
        return getattr(bpy.context, key)


def capture(cls, key):
    original = cls.invoke

    def execute(self, context):
        # Background dispatch lacks an event; only the final popup is stubbed.
        # The owner and every RNA assignment/update callback are genuine.
        assert isinstance(self, bpy.types.Operator)
        assert isinstance(self.properties, bpy.types.OperatorProperties)
        assert original(self, DialogContext(), None) == {"RUNNING_MODAL"}
        if key == "projection":
            assert not hasattr(self.properties, "_feature")
            assert self.target == "reference" and self.replacement == "0"
            self.target = "reference"
            assert self.replacement == "0" and not self.reverse
            self.cancel(context)
        else:
            captured[key] = {
                field: getattr(self, field)
                for field in (
                    "original_json",
                    "feature_id",
                    "feature_label",
                    "base",
                    "radius",
                    "face_a",
                    "face_b",
                    "edge_mode",
                    "shell_mode",
                    "opening_face",
                )
            }
        return {"CANCELLED"}

    cls.execute = execute


capture(projection_repair_ui.MCAD_OT_replace_projection_reference, "projection")
capture(solid_operators.MCAD_OT_edit_solid_feature, "solid")
register()
window = bpy.context.window
area = next(a for a in window.screen.areas if a.type == "VIEW_3D")
region = next(r for r in area.regions if r.type == "WINDOW")
with bpy.context.temp_override(window=window, area=area, region=region):
    context = bpy.context
    state = context.scene.mechanical_cad
    data = json.loads(Path(os.environ["MCAD_PROJECTION_FIXTURE"]).read_text())
    assert document_state._commit_candidate(context, data, "")
    before = state.document_json
    assert bpy.ops.mcad.replace_projection_reference("INVOKE_DEFAULT", feature_id="target") == {
        "CANCELLED"
    }
    assert state.document_json == before

    assert bpy.ops.mcad.new_document(name="RNA blend editor") == {"FINISHED"}
    assert bpy.ops.mcad.add_rectangle(width=20, height=30) == {"FINISHED"}
    assert bpy.ops.mcad.add_extrude(profile=state.active_feature, length=10) == {"FINISHED"}
    base = state.active_feature
    assert bpy.ops.mcad.add_solid_feature(
        kind="fillet",
        base=base,
        radius="1",
        edge_mode="PAIR",
        face_a=base + "/face/cap.end",
        face_b=base + "/face/side.y_min",
    ) == {"FINISHED"}
    feature = state.active_feature
    before = state.document_json
    assert bpy.ops.mcad.edit_solid_feature("INVOKE_DEFAULT", feature_id=feature) == {"CANCELLED"}
    values = captured["solid"]
    assert values["base"] == base and values["face_a"] == base + "/face/cap.end"
    values["radius"] = "1 + 0.25"
    values["face_a"] = base + "/face/cap.start"
    assert bpy.ops.mcad.edit_solid_feature(
        "INVOKE_DEFAULT", feature_id=feature, resume_json=json.dumps(values)
    ) == {"CANCELLED"}
    values = captured["solid"]
    assert values["radius"] == "1 + 0.25" and values["face_a"] == base + "/face/cap.start"
    assert state.document_json == before
print("REPAIR_REAL_RNA_INVOKE_OK")
unregister()
